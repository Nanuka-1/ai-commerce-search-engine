DEFAULT_LANGUAGE = "ka"
GEORGIAN_CHAR_RANGE = range(0x10A0, 0x10FF + 1)


def resolve_language(text: str | None, locale: str | None = None) -> str:
    # 1. Грузинские буквы в сообщении → грузинский.
    # 2. Иначе текст "нейтральный" (nike 42, SKU) → язык страницы сайта (locale из API).
    # 3. locale нет или неизвестен → грузинский (основной язык магазина).
    if text and any(ord(char) in GEORGIAN_CHAR_RANGE for char in text):
        return "ka"
    if locale in TRANSLATIONS:
        return locale
    return DEFAULT_LANGUAGE


def translate(key: str, locale: str) -> str:
    lang = locale if locale in TRANSLATIONS else DEFAULT_LANGUAGE
    return TRANSLATIONS[lang].get(key, key)